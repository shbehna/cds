"""Resources of the demo in a Databricks workspace.

The deployment uploads the framework wheel, the service notebooks and the data products
of the demo to a workspace folder, publishes the quality dashboard, and creates the job
running the services in order:

    schema --> metadata
           --> transformation --> quality --> scd

The job has no schedule: it runs on demand.

Depending on the stack, the deployment also creates the catalog of the environment
(createCatalog), uploads the synthetic data set (cds-demo/csv/testdata) next to the
files of the register, the job then loading it instead of them (syntheticData), and
masks the classified columns (masking): see governance.
"""

from __future__ import annotations

import hashlib
import json
import posixpath
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path

import pulumi
import pulumi_databricks as databricks
import tomllib
from sql_statement import SqlStatement

REPOSITORY = Path(__file__).resolve().parents[2]
FRAMEWORK = REPOSITORY / "cds-framework"
PRODUCTS = REPOSITORY / "cds-demo" / "products"
# The quality dashboard, generated from the contracts by cds-demo/dashboards/quality_dashboard.py.
QUALITY_DASHBOARD = REPOSITORY / "cds-demo" / "dashboards" / "req_quality.lvdash.json"
# The synthetic data set, generated by cds-demo/csv/generate_testdata.py.
TESTDATA = REPOSITORY / "cds-demo" / "csv" / "testdata"
# What the deployment needs to know of the contracts, generated by cds-demo/manifest/manifest.py.
MANIFEST = REPOSITORY / "cds-demo" / "manifest" / "req_manifest.json"
# Privileges of the readers of a catalog created by the deployment.
READER_PRIVILEGES = ["USE_CATALOG", "USE_SCHEMA", "SELECT"]

# Services run by the job, with the services they wait for.
TASKS: dict[str, list[str]] = {
    "schema": [],
    "metadata": ["schema"],
    "transformation": ["schema"],
    "quality": ["transformation"],
    "scd": ["quality"],
}
ENVIRONMENT_KEY = "cds"

# Schema of the catalog of an environment holding the masking function, created by the
# deployment, and the function.
GOVERNANCE_SCHEMA = "governance"
MASK_FUNCTION = "mask"
# Principals whose queries are masked: every user of the account, except the exempted ones.
MASKED_PRINCIPALS = ["account users"]


@dataclass(frozen=True)
class Settings:
    """Settings of a deployment, read from the configuration of the Pulumi stack."""

    environment: str
    source_path: str
    workspace_root: str
    service_principal: str | None = None
    data_product: str = "donnees_qc.req"
    # Schema of the tables of the data product, following the naming convention of the
    # donnees_qc group; their catalog is the environment.
    schema: str = "donnees_qc_req"
    # SQL warehouse running the queries of the dashboard.
    warehouse_name: str = "Serverless Starter Warehouse"
    host: str | None = None
    # Version 5 is the serverless environment targeted by the local environment of the
    # repository (pyproject.toml, [tool.databricks.environment]).
    environment_version: str = "5"
    dqx_version: str = "0.17.0"
    max_workers: int = 4
    # Whether the job loads the synthetic data set instead of the files of the register.
    synthetic_data: bool = False
    # Whether the deployment creates the catalog of the environment, owned by the
    # deployment service principal, with an optional storage location and readers.
    create_catalog: bool = False
    catalog_storage_root: str | None = None
    catalog_readers: tuple[str, ...] = ()
    # Whether the deployment masks the columns of the classifications masked_classifications
    # (none if empty), except for the deployment service principal and the exempted
    # principals. The classification tag is a governed tag, created by the deployment if
    # create_tag_policies.
    masking: bool = False
    masked_classifications: tuple[str, ...] = ("restricted",)
    masking_exempt_principals: tuple[str, ...] = ()
    create_tag_policies: bool = False
    manifest: Path = field(default=MANIFEST)
    wheel_directory: Path = field(default=REPOSITORY / "dist")
    testdata_directory: Path = field(default=TESTDATA)

    @classmethod
    def from_stack(cls) -> Settings:
        config = pulumi.Config()
        environment = config.require("environment")
        return cls(
            environment=environment,
            source_path=config.require("sourcePath"),
            workspace_root=config.get("workspaceRoot") or f"/Shared/cds-demo/{environment}",
            service_principal=pulumi.Config("databricks").get("clientId"),
            host=pulumi.Config("databricks").get("host"),
            schema=config.get("schema") or cls.schema,
            warehouse_name=config.get("warehouseName") or cls.warehouse_name,
            environment_version=config.get("environmentVersion") or cls.environment_version,
            dqx_version=config.get("dqxVersion") or cls.dqx_version,
            max_workers=config.get_int("maxWorkers") or cls.max_workers,
            synthetic_data=config.get_bool("syntheticData") or False,
            create_catalog=config.get_bool("createCatalog") or False,
            catalog_storage_root=config.get("catalogStorageRoot"),
            catalog_readers=string_list("catalogReaders", config.get_object("catalogReaders")),
            masking=config.get_bool("masking") or False,
            masked_classifications=string_list(
                "maskedClassifications", config.get_object("maskedClassifications"), cls.masked_classifications
            ),
            masking_exempt_principals=string_list(
                "maskingExemptPrincipals", config.get_object("maskingExemptPrincipals")
            ),
            create_tag_policies=config.get_bool("createTagPolicies") or False,
        )


def string_list(key: str, value: object, default: tuple[str, ...] = ()) -> tuple[str, ...]:
    """Returns the value of a stack variable holding a list of strings, its default if it is not set.

    Raises:
        ValueError: If the value is not a list of strings.
    """
    if value is None:
        return default
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise ValueError(f'cds-demo:{key} must be a list of strings, such as ["a", "b"], not {value!r}.')
    return tuple(value)


def framework_wheel(directory: Path) -> Path:
    """Returns the wheel of the current version of the framework.

    Raises:
        FileNotFoundError: If the wheel was not built.
    """
    project = tomllib.loads((FRAMEWORK / "pyproject.toml").read_text(encoding="utf-8"))
    wheel = directory / f"cds_framework-{project['project']['version']}-py3-none-any.whl"
    if not wheel.is_file():
        raise FileNotFoundError(
            f"{wheel} does not exist. Build it first, from the root of the repository: "
            "uv build --package cds-framework --wheel --out-dir dist"
        )
    return wheel


def product_files() -> list[Path]:
    """Returns the files of the data products: contracts and configuration modules."""
    return [
        path
        for path in sorted(PRODUCTS.rglob("*"))
        if path.is_file() and path.suffix in (".py", ".yaml", ".yml") and "__pycache__" not in path.parts
    ]


def folders(root: str, paths: Iterable[str]) -> list[str]:
    """Returns the root and the folders under it holding the paths, parents first."""
    found = {root}
    for path in paths:
        folder = posixpath.dirname(path)
        while folder.startswith(f"{root}/"):
            found.add(folder)
            folder = posixpath.dirname(folder)
    return sorted(found, key=lambda folder: (folder.count("/"), folder))


def testdata_files(directory: Path) -> list[Path]:
    """Returns the files of the synthetic data set.

    Raises:
        FileNotFoundError: If the directory holds no CSV file.
    """
    files = sorted(directory.glob("*.csv"))
    if not files:
        raise FileNotFoundError(
            f"{directory} holds no CSV file. Generate the synthetic data set first, from the root of the "
            "repository: uv run python cds-demo/csv/generate_testdata.py"
        )
    return files


def catalog(settings: Settings) -> databricks.Catalog:
    """Creates the catalog of the environment, and grants its readers access to its tables.

    The deployment service principal owns the catalog, and so the schemas and tables the
    job creates in it. The catalog is protected: Pulumi does not delete it, nor its data.
    """
    created = databricks.Catalog(
        "catalog",
        name=settings.environment,
        comment=f"CDS demo, {settings.environment} environment: the data products of the demo.",
        storage_root=settings.catalog_storage_root,
        properties={"project": "cds-demo", "environment": settings.environment},
        opts=pulumi.ResourceOptions(protect=True),
    )
    for principal in settings.catalog_readers:
        databricks.Grant(
            f"catalog-reader:{principal}",
            catalog=created.name,
            principal=principal,
            privileges=READER_PRIVILEGES,
        )
    return created


def manifest_classification(path: Path) -> tuple[str, list[str]]:
    """Returns the key and the allowed values of the classification tag, from the manifest.

    Raises:
        FileNotFoundError: If the manifest was not generated.
    """
    if not path.is_file():
        raise FileNotFoundError(
            f"{path} does not exist. Generate it first, from the root of the repository: "
            "uv run python cds-demo/manifest/manifest.py"
        )
    classification = json.loads(path.read_text(encoding="utf-8"))["classification"]
    return str(classification["tag"]), [str(value) for value in classification["values"]]


def governance(
    settings: Settings, warehouse_id: pulumi.Input[str], created_catalog: databricks.Catalog | None
) -> list[pulumi.Resource]:
    """Masks the classified columns of the tables of the catalog of the environment.

    The services of the job tag each column with its classification (cds-demo/manifest),
    the schema and scd services before writing to it. An ABAC policy of the catalog masks
    the columns tagged with each masked classification, with the masking function of the
    governance schema, for every user of the account except the deployment service
    principal, which runs the job and must read the data as it is, and the exempted
    principals. The function masks strings: a masked classification only applies to
    STRING columns (cds-demo/tests/test_manifest.py).

    The classification tag is a governed tag: the policy needs it. Tag policies belong to
    the account, shared by the environments: only one stack creates it (createTagPolicies).
    It is protected, so that destroying that stack does not remove the masking of the
    others: unprotect it first (see the README).

    Returns:
        The resources the job needs: the tag policy, when the deployment creates it.

    Raises:
        ValueError: If the service principal is unknown, or a masked classification is not
            a value of the classification tag.
    """
    if not settings.service_principal:
        raise ValueError("The masking needs the service principal of the job (databricks:clientId), which it exempts.")
    tag, values = manifest_classification(settings.manifest)
    unknown = sorted(set(settings.masked_classifications) - set(values))
    if unknown:
        raise ValueError(f"Unknown masked classification(s) {', '.join(unknown)}: the values are {', '.join(values)}.")

    tag_policy = (
        databricks.TagPolicy(
            f"tag-policy:{tag}",
            tag_key=tag,
            description="Classification of the columns of the CDS demo, from their data contracts (cds-demo/manifest).",
            values=[databricks.TagPolicyValueArgs(name=value) for value in values],
            opts=pulumi.ResourceOptions(protect=True),
        )
        if settings.create_tag_policies
        else None
    )
    in_catalog = pulumi.ResourceOptions(depends_on=[created_catalog] if created_catalog else None)
    schema = databricks.Schema(
        "governance-schema",
        catalog_name=settings.environment,
        name=GOVERNANCE_SCHEMA,
        comment="CDS demo: the masking function of the classified columns.",
        opts=in_catalog,
    )
    function = f"{settings.environment}.{GOVERNANCE_SCHEMA}.{MASK_FUNCTION}"
    quoted = ".".join(f"`{part}`" for part in function.split("."))
    mask = SqlStatement(
        "mask-function",
        warehouse_id=warehouse_id,
        object_name=function,
        create=(
            f"CREATE OR REPLACE FUNCTION {quoted}(value STRING) RETURNS STRING "
            "COMMENT 'CDS demo: masks a classified column.' "
            "RETURN CASE WHEN value IS NULL THEN NULL ELSE '****' END"
        ),
        delete=f"DROP FUNCTION IF EXISTS {quoted}",
        host=settings.host,
        client_id=settings.service_principal,
        opts=pulumi.ResourceOptions(depends_on=[schema]),
    )
    for value in settings.masked_classifications:
        databricks.PolicyInfo(
            f"mask-policy:{value}",
            name=f"mask_{value}",
            comment=f"CDS demo: masks the columns classified {value}, except for the service principal of the job.",
            on_securable_type="CATALOG",
            on_securable_fullname=settings.environment,
            for_securable_type="TABLE",
            policy_type="POLICY_TYPE_COLUMN_MASK",
            to_principals=MASKED_PRINCIPALS,
            except_principals=[settings.service_principal, *settings.masking_exempt_principals],
            match_columns=[
                databricks.PolicyInfoMatchColumnArgs(
                    alias="masked_column", condition=f"has_tag_value('{tag}', '{value}')"
                )
            ],
            column_mask=databricks.PolicyInfoColumnMaskArgs(function_name=function, on_column="masked_column"),
            opts=pulumi.ResourceOptions(depends_on=[mask, *([tag_policy] if tag_policy else [])]),
        )
    pulumi.export("mask_function", function)
    return [tag_policy] if tag_policy else []


def testdata_uploads(settings: Settings) -> list[databricks.File]:
    """Uploads the synthetic data set to the folder of the files of the register."""
    folder = settings.source_path.rstrip("/")
    return [
        databricks.File(f"testdata/{path.name}", path=f"{folder}/{path.name}", source=str(path))
        for path in testdata_files(settings.testdata_directory)
    ]


def deploy(settings: Settings) -> databricks.Job:
    """Declares the resources of the demo and returns the job."""
    root = settings.workspace_root.rstrip("/")
    warehouse = databricks.get_sql_warehouse_output(name=settings.warehouse_name)
    # The job runs once the catalog, the files it reads and the governed tags it applies exist.
    prerequisites: list[pulumi.Resource] = []
    created_catalog = catalog(settings) if settings.create_catalog else None
    if created_catalog:
        prerequisites.append(created_catalog)
    if settings.synthetic_data:
        prerequisites.extend(testdata_uploads(settings))
    if settings.masking:
        prerequisites.extend(governance(settings, warehouse.id, created_catalog))

    wheel = framework_wheel(settings.wheel_directory)
    # A folder named after the content of the wheel: serverless environments are cached by
    # their dependencies, so a new build must get a new path to be installed.
    digest = hashlib.sha256(wheel.read_bytes()).hexdigest()[:16]
    wheel_path = f"{root}/wheels/{digest}/{wheel.name}"
    notebook_paths = {service: f"{root}/notebooks/{service}" for service in TASKS}
    product_paths = {path: f"{root}/products/{path.relative_to(PRODUCTS).as_posix()}" for path in product_files()}
    dashboard_folder = f"{root}/dashboards"

    # The folders are created first, each after its parent: the provider creates a missing
    # parent folder when it uploads a file, but not reliably when files are uploaded in
    # parallel.
    directories: dict[str, databricks.Directory] = {}
    paths = [
        wheel_path,
        *notebook_paths.values(),
        *product_paths.values(),
        f"{dashboard_folder}/{QUALITY_DASHBOARD.name}",
    ]
    for folder in folders(root, paths):
        parent = directories.get(posixpath.dirname(folder))
        directories[folder] = databricks.Directory(
            f"folder:{posixpath.relpath(folder, root)}",
            path=folder,
            opts=pulumi.ResourceOptions(depends_on=[parent] if parent else None),
        )

    def in_folder(path: str) -> pulumi.ResourceOptions:
        return pulumi.ResourceOptions(depends_on=[directories[posixpath.dirname(path)]])

    wheel_file = databricks.WorkspaceFile(
        "framework-wheel", path=wheel_path, source=str(wheel), opts=in_folder(wheel_path)
    )

    notebooks = {
        service: databricks.Notebook(
            f"notebook-{service}",
            path=path,
            source=str(FRAMEWORK / "notebooks" / f"{service}.py"),
            language="PYTHON",
            opts=in_folder(path),
        )
        for service, path in notebook_paths.items()
    }

    products = [
        databricks.WorkspaceFile(
            f"products/{source.relative_to(PRODUCTS).as_posix()}",
            path=path,
            source=str(source),
            opts=in_folder(path),
        )
        for source, path in product_paths.items()
    ]

    parameters = {
        "environment": settings.environment,
        "roots": f"/Workspace{root}/products",
        "data_product": settings.data_product,
        "source_path": settings.source_path,
        "max_workers": str(settings.max_workers),
        # Read by the transformations of the demo (products/donnees_qc/req/sources.py).
        "synthetic_data": "true" if settings.synthetic_data else "false",
    }
    job = databricks.Job(
        "pipeline",
        name=f"cds-demo-req-{settings.environment}",
        description=(
            "CDS demo: builds the donnees_qc.req data product (Registraire des entreprises du Québec) "
            "from its data contracts."
        ),
        parameters=[databricks.JobParameterArgs(name=name, default=value) for name, value in parameters.items()],
        environments=[
            databricks.JobEnvironmentArgs(
                environment_key=ENVIRONMENT_KEY,
                spec=databricks.JobEnvironmentSpecArgs(
                    environment_version=settings.environment_version,
                    dependencies=[
                        wheel_file.path.apply(lambda path: f"/Workspace{path}"),
                        f"databricks-labs-dqx=={settings.dqx_version}",
                    ],
                ),
            )
        ],
        tasks=[
            databricks.JobTaskArgs(
                task_key=service,
                description=f"CDS {service} service",
                depends_ons=[databricks.JobTaskDependsOnArgs(task_key=upstream) for upstream in upstreams],
                environment_key=ENVIRONMENT_KEY,
                notebook_task=databricks.JobTaskNotebookTaskArgs(
                    notebook_path=notebooks[service].path, source="WORKSPACE"
                ),
                max_retries=0,
                timeout_seconds=2 * 3600,
            )
            for service, upstreams in TASKS.items()
        ],
        max_concurrent_runs=1,
        run_as=(
            databricks.JobRunAsArgs(service_principal_name=settings.service_principal)
            if settings.service_principal
            else None
        ),
        tags={"project": "cds-demo", "environment": settings.environment, "data_product": settings.data_product},
        opts=pulumi.ResourceOptions(depends_on=[*products, *prerequisites]),
    )
    dashboard = quality_dashboard(settings, dashboard_folder, directories[dashboard_folder], warehouse.id)
    pulumi.export("job_id", job.id)
    pulumi.export("job_url", job.url)
    pulumi.export("workspace_root", root)
    pulumi.export("dashboard_id", dashboard.dashboard_id)
    if settings.host:
        pulumi.export(
            "dashboard_url",
            pulumi.Output.concat(settings.host.rstrip("/"), "/dashboardsv3/", dashboard.dashboard_id, "/published"),
        )
    return job


def quality_dashboard(
    settings: Settings, folder: str, directory: databricks.Directory, warehouse_id: pulumi.Input[str]
) -> databricks.Dashboard:
    """Publishes the quality dashboard of the data product.

    Its queries name the tables without catalog nor schema: the dashboard sets them for the
    environment. They run on the SQL warehouse with the credentials of the deployment
    service principal, which owns the tables.
    """
    return databricks.Dashboard(
        "quality-dashboard",
        display_name=f"REQ data quality ({settings.environment})",
        parent_path=folder,
        serialized_dashboard=QUALITY_DASHBOARD.read_text(encoding="utf-8"),
        warehouse_id=warehouse_id,
        dataset_catalog=settings.environment,
        dataset_schema=settings.schema,
        embed_credentials=True,
        opts=pulumi.ResourceOptions(depends_on=[directory]),
    )
