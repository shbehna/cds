def catalog(settings: Settings) -> databricks.Catalog:
    """Creates the catalog of the environment, and grants its readers access to its tables.

    The deployment service principal owns the catalog, and so the schemas and tables the
    job creates in it. The catalog is protected: Pulumi does not delete it, nor its data.
    """
    created = databricks.Catalog(
        "catalog",
        name=settings.environment,
        comment=f"CDS demo, {settings.environment} environment: the data products of the demo.",
        storage_root=settings.catalog_storage_root,
        properties={"project": "cds-demo", "environment": settings.environment},
        opts=pulumi.ResourceOptions(protect=True),
    )
    for principal in settings.catalog_readers:
        databricks.Grant(
            f"catalog-reader:{principal}",
            catalog=created.name,
            principal=principal,
            privileges=READER_PRIVILEGES,
        )
    return created


def load_manifest(path: Path) -> dict[str, Any]:
    """Reads the manifest of the data product, generated from the contracts.

    Raises:
        FileNotFoundError: If the manifest was not generated.
    """
    if not path.is_file():
        raise FileNotFoundError(
            f"{path} does not exist. Generate it first, from the root of the repository: "
            "uv run python cds-demo/manifest/manifest.py"
        )
    manifest: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return manifest


def manifest_classification(manifest: Mapping[str, Any]) -> tuple[str, list[str]]:
    """Returns the key and the allowed values of the classification tag, from the manifest."""
    classification = manifest["classification"]
    return str(classification["tag"]), [str(value) for value in classification["values"]]


def environment_query(query: str, environment: str) -> str:
    """Returns a query of the manifest for an environment, replacing its placeholder.

    Raises:
        ValueError: If the environment is not a lowercase identifier, which the query can
            hold as a name or a string.
    """
    if not re.fullmatch(r"[a-z][a-z0-9_]*", environment):
        raise ValueError(f"Invalid environment {environment!r}: expected a lowercase identifier such as nprod.")
    return query.replace(ENVIRONMENT_PLACEHOLDER, environment)


def job_schedule(settings: Settings, manifest: Mapping[str, Any]) -> databricks.JobScheduleArgs | None:
    """The schedule of the job: the frequency SLA of the contracts, from the manifest."""
    schedule = manifest.get("schedule")
    if not schedule:
        return None
    return databricks.JobScheduleArgs(
        quartz_cron_expression=schedule["quartz"],
        timezone_id=settings.timezone,
        pause_status="PAUSED" if settings.pause_schedule else "UNPAUSED",
    )


def alert_emails_from_environment(environ: Mapping[str, str] | None = None) -> pulumi.Output[list[str]] | None:
    """Reads the addresses receiving the alerts from the ALERT_EMAILS environment variable.

    The workflow sets it from the GitHub secret of the same name. The addresses are
    separated by commas, semicolons or spaces.

    Returns:
        The addresses, as a secret output; ``None`` when the variable is not set or empty.

    Raises:
        ValueError: If a value is not an email address. The message does not show the addresses.
    """
    value = (os.environ if environ is None else environ).get(ALERT_EMAILS_VARIABLE, "")
    addresses = [address for address in re.split(r"[\s,;]+", value) if address]
    if not addresses:
        return None
    invalid = [str(position) for position, address in enumerate(addresses, 1) if "@" not in address]
    if invalid:
        raise ValueError(
            f"{ALERT_EMAILS_VARIABLE}: the value number {', '.join(invalid)} is not an email address; "
            "separate the addresses with commas."
        )
    return pulumi.Output.secret(addresses)


def alert_addresses(
    recipients: Sequence[str], emails: pulumi.Input[Sequence[str]] | None
) -> pulumi.Input[Sequence[str]]:
    """The addresses receiving the alerts: the recipients of the manifest, and the alert emails.

    Returns:
        The recipients without alert emails; otherwise an output, secret when the alert
        emails are.
    """
    if emails is None:
        return list(dict.fromkeys(recipients))
    return pulumi.Output.from_input(emails).apply(lambda value: list(dict.fromkeys([*recipients, *value])))


def alerts(
    settings: Settings,
    manifest: Mapping[str, Any],
    folder: str,
    directory: databricks.Directory,
    warehouse_id: pulumi.Input[str],
    addresses: pulumi.Input[Sequence[str]],
) -> list[databricks.AlertV2]:
    """Creates the SQL alerts of the SLA of the contracts, from the manifest.

    Each alert runs its query on the SQL warehouse, as the deployment service principal,
    on the schedule of its SLA. The query returns a row per table: the alert triggers when
    a table breaks its SLA (the maximum of the exceeded column is above 0), and sends an
    email to the support channels of the contracts and the alert emails when it triggers
    and when it is back to normal. Without address, the alerts send nothing.

    The alert emails come from a GitHub secret (ALERT_EMAILS): the addresses of the
    notification destination are a secret output, kept encrypted in the state of the stack.

    Args:
        settings: The settings of the deployment.
        manifest: The manifest of the data product.
        folder: The workspace folder of the alerts.
        directory: The resource of the folder.
        warehouse_id: The SQL warehouse running the queries.
        addresses: The addresses receiving the alerts (see alert_addresses).
    """
    definitions = manifest.get("alerts") or []
    destination = (
        databricks.NotificationDestination(
            "alert-destination",
            display_name=f"CDS demo alerts ({settings.environment})",
            config=databricks.NotificationDestinationConfigArgs(
                email=databricks.NotificationDestinationConfigEmailArgs(addresses=addresses)
            ),
        )
        if definitions and addresses
        else None
    )
    notification = (
        databricks.AlertV2EvaluationNotificationArgs(
            subscriptions=[databricks.AlertV2EvaluationNotificationSubscriptionArgs(destination_id=destination.id)],
            notify_on_ok=True,
        )
        if destination
        else None
    )
    created = []
    for definition in definitions:
        created.append(
            databricks.AlertV2(
                f"alert:{definition['name']}",
                display_name=f"REQ {definition['title']} SLA ({settings.environment})",
                query_text=environment_query(definition["query"], settings.environment),
                warehouse_id=warehouse_id,
                parent_path=folder,
                evaluation=databricks.AlertV2EvaluationArgs(
                    source=databricks.AlertV2EvaluationSourceArgs(name=EXCEEDED_COLUMN, aggregation="MAX"),
                    comparison_operator="GREATER_THAN",
                    threshold=databricks.AlertV2EvaluationThresholdArgs(
                        value=databricks.AlertV2EvaluationThresholdValueArgs(double_value=0)
                    ),
                    empty_result_state="OK",
                    notification=notification,
                ),
                schedule=databricks.AlertV2ScheduleArgs(
                    quartz_cron_schedule=definition["quartz"], timezone_id=settings.timezone, pause_status="UNPAUSED"
                ),
                run_as=(
                    databricks.AlertV2RunAsArgs(service_principal_name=settings.service_principal)
                    if settings.service_principal
                    else None
                ),
                purge_on_delete=True,
                opts=pulumi.ResourceOptions(depends_on=[directory]),
            )
        )
    return created


def governance(
    settings: Settings,
    manifest: Mapping[str, Any],
    warehouse_id: pulumi.Input[str],
    created_catalog: databricks.Catalog | None,
) -> list[pulumi.Resource]:
    """Masks the classified columns of the tables of the catalog of the environment.

    The services of the job tag each column with its classification (cds-demo/manifest),
    the schema and scd services before writing to it. An ABAC policy of the catalog masks
    the columns tagged with each masked classification, with the masking function of the
    governance schema, for every user of the account except the deployment service
    principal, which runs the job and must read the data as it is, and the exempted
    principals. The function masks strings: a masked classification only applies to
    STRING columns (cds-demo/tests/test_manifest.py).

    The classification tag is a governed tag: the policy needs it. Tag policies belong to
    the account, shared by the environments: only one stack creates it (createTagPolicies).
    It is protected, so that destroying that stack does not remove the masking of the
    others: unprotect it first (see the README). When the deployment creates it, the
    policies wait for it to propagate (TAG_POLICY_PROPAGATION_SECONDS).

    Returns:
        The resources the job needs: the tag policy and its propagation, when the deployment
        creates it.

    Raises:
        ValueError: If the service principal is unknown, or a masked classification is not
            a value of the classification tag.
    """
    if not settings.service_principal:
        raise ValueError("The masking needs the service principal of the job (databricks:clientId), which it exempts.")
    tag, values = manifest_classification(manifest)
    unknown = sorted(set(settings.masked_classifications) - set(values))
    if unknown:
        raise ValueError(f"Unknown masked classification(s) {', '.join(unknown)}: the values are {', '.join(values)}.")

    tag_policy = (
        databricks.TagPolicy(
            f"tag-policy:{tag}",
            tag_key=tag,
            description="Classification of the columns of the CDS demo, from their data contracts (cds-demo/manifest).",
            values=[databricks.TagPolicyValueArgs(name=value) for value in values],
            opts=pulumi.ResourceOptions(protect=True),
        )
        if settings.create_tag_policies
        else None
    )
    propagated = (
        Delay(
            f"tag-policy-propagation:{tag}",
            seconds=TAG_POLICY_PROPAGATION_SECONDS,
            trigger=tag_policy.id,
            opts=pulumi.ResourceOptions(depends_on=[tag_policy]),
        )
        if tag_policy
        else None
    )
    in_catalog = pulumi.ResourceOptions(depends_on=[created_catalog] if created_catalog else None)
    schema = databricks.Schema(
        "governance-schema",
        catalog_name=settings.environment,
        name=GOVERNANCE_SCHEMA,
        comment="CDS demo: the masking function of the classified columns.",
        opts=in_catalog,
    )
    function = f"{settings.environment}.{GOVERNANCE_SCHEMA}.{MASK_FUNCTION}"
    quoted = ".".join(f"`{part}`" for part in function.split("."))
    mask = SqlStatement(
        "mask-function",
        warehouse_id=warehouse_id,
        object_name=function,
        create=(
            f"CREATE OR REPLACE FUNCTION {quoted}(value STRING) RETURNS STRING "
            "COMMENT 'CDS demo: masks a classified column.' "
            "RETURN CASE WHEN value IS NULL THEN NULL ELSE '****' END"
        ),
        delete=f"DROP FUNCTION IF EXISTS {quoted}",
        host=settings.host,
        client_id=settings.service_principal,
        opts=pulumi.ResourceOptions(depends_on=[schema]),
    )
    for value in settings.masked_classifications:
        databricks.PolicyInfo(
            f"mask-policy:{value}",
            name=f"mask_{value}",
            comment=f"CDS demo: masks the columns classified {value}, except for the service principal of the job.",
            on_securable_type="CATALOG",
            on_securable_fullname=settings.environment,
            for_securable_type="TABLE",
            policy_type="POLICY_TYPE_COLUMN_MASK",
            to_principals=MASKED_PRINCIPALS,
            except_principals=[settings.service_principal, *settings.masking_exempt_principals],
            match_columns=[
                databricks.PolicyInfoMatchColumnArgs(
                    alias="masked_column", condition=f"has_tag_value('{tag}', '{value}')"
                )
            ],
            column_mask=databricks.PolicyInfoColumnMaskArgs(function_name=function, on_column="masked_column"),
            opts=pulumi.ResourceOptions(depends_on=[mask, *([propagated] if propagated else [])]),
        )
    pulumi.export("mask_function", function)
    return [tag_policy, propagated] if tag_policy and propagated else []


def discover_domains(manifest: Mapping[str, Any]) -> list[pulumi.Resource]:
    """Creates the Discover domains of the contracts, and their governed tags.

    The metadata step of the job tags each table with the governed tag of its Discover
    domain, from its contract (cds-demo/manifest): Économie/Registraire des entreprises du
    Québec, the subdomain of the register in the Économie domain. A domain is built on its
    governed tag, and a subdomain created under its parent: the manifest lists the domains
    parents first. They are published, presented as DOMAINS describes them.

    The governed tags and the domains belong to the account, shared by the environments:
    only one stack creates them (createDomains), protected, so that destroying it does not
    remove the domains of the others. The domains, and the job applying the tags, wait for
    the new governed tags to propagate (TAG_POLICY_PROPAGATION_SECONDS).

    Returns:
        The governed tags, their propagation and the domains: the job waits for them.

    Raises:
        ValueError: If a domain is not described in DOMAINS, or does not come after its
            parent in the manifest. Nothing is created then.
    """
    parents: dict[str, str | None] = {}
    for domain in manifest.get("domains") or []:
        tag, parent = str(domain["tag"]), domain.get("parent")
        if parent is not None and parent not in parents:
            raise ValueError(f"The Discover domain {tag!r} needs its parent {parent!r} before it in the manifest.")
        parents[tag] = parent
    missing = [tag for tag in parents if tag not in DOMAINS]
    if missing:
        raise ValueError(f"Describe the Discover domain(s) {', '.join(missing)} in DOMAINS (pipeline.py).")
    if not parents:
        return []
    policies = [
        databricks.TagPolicy(
            f"tag-policy:{tag}",
            tag_key=tag,
            description=f"Discover domain {tag} of the CDS demo: the tables tagged with it belong to it.",
            opts=pulumi.ResourceOptions(protect=True),
        )
        for tag in parents
    ]
    propagated = Delay(
        "tag-policy-propagation:domains",
        seconds=TAG_POLICY_PROPAGATION_SECONDS,
        trigger=pulumi.Output.all(*(policy.id for policy in policies)).apply(lambda ids: ",".join(ids)),
        opts=pulumi.ResourceOptions(depends_on=policies),
    )
    domains: dict[str, databricks.Domain] = {}
    for tag, parent in parents.items():
        domains[tag] = databricks.Domain(
            f"domain:{tag}",
            tag_key=tag,
            subtitle=DOMAINS[tag].subtitle,
            description=DOMAINS[tag].description,
            parent_domain_id=domains[parent].domain_id if parent else None,
            draft=False,
            opts=pulumi.ResourceOptions(protect=True, depends_on=[propagated]),
        )
    return [*policies, propagated, *domains.values()]


