"""Quality summary: the statistics of the checks of each table, against the thresholds of its contract.

After checking a table, the quality service appends its statistics to the summary table
of its schema (``QualitySettings.summary_table``, ``_quality_summary`` by default: the
tables generated by the framework start with ``_``, as its columns do). A run appends,
for each table:

- a row per measure of the table: ``errorRate``, the share of its rows with errors, held
  to the ``errorRate`` SLA of the contract, and ``warningRate``, the share of its rows
  with warnings;
- a row per check (``failedRows``): the rows it flags. A check implementing a ``quality``
  rule of the contract with thresholds (``mustBe``, ``mustBeLessThan``... in ``rows`` or
  ``percent``) gets a row per threshold; the checks without threshold, such as those
  inferred from ``required`` or the primary key, get a row with their statistics only.
  The checks of a ``rowCount`` rule measure the number of rows of the table instead.

``passed`` tells whether the ``actual`` value meets the threshold, ``NULL`` without
threshold. The rows of a run share their ``checked_at`` time, and the ``run_id`` runtime
parameter, if set (for example ``{{job.run_id}}``): the latest row of a table and check
gives its current state.
"""

from __future__ import annotations

import math
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import datetime
from typing import TYPE_CHECKING, Any

from cds.config import QualitySettings, resolved
from cds.errors import ConfigurationError, ContractError
from cds.odcs import QualityRule
from cds.sql import quote_identifier, quote_name, string_literal

if TYPE_CHECKING:
    from cds.context import ServiceContext
    from cds.data_context import Table

# Measures of the summary rows.
ERROR_RATE = "errorRate"
WARNING_RATE = "warningRate"
FAILED_ROWS = "failedRows"
ROW_COUNT = "rowCount"

ROWS = "rows"
PERCENT = "percent"
_UNITS: Mapping[str, str] = {"rows": ROWS, "row": ROWS, "percent": PERCENT, "%": PERCENT}

_BETWEEN = frozenset({"mustBeBetween", "mustNotBeBetween"})


@dataclass(frozen=True)
class Threshold:
    """A threshold of a quality rule, such as ``mustBeLessThan: 5`` percent.

    Attributes:
        operator: The ODCS operator, such as ``mustBeLessThan``.
        value: The value it compares to; the lower bound of ``mustBeBetween`` and
            ``mustNotBeBetween``, whose bounds are included.
        high: The upper bound of ``mustBeBetween`` and ``mustNotBeBetween``.
        unit: ``rows`` or ``percent`` (of the rows of the table).
        metric: What the threshold measures: ``failedRows`` (the rows a check flags),
            ``rowCount`` (the rows of the table) or ``errorRate``.
    """

    operator: str
    value: float
    high: float | None = None
    unit: str = ROWS
    metric: str = FAILED_ROWS

    def passes(self, actual: float) -> bool:
        """Whether a value meets the threshold."""
        low, high = self.value, self.high if self.high is not None else self.value
        return {
            "mustBe": lambda: actual == low,
            "mustNotBe": lambda: actual != low,
            "mustBeGreaterThan": lambda: actual > low,
            "mustBeGreaterOrEqualTo": lambda: actual >= low,
            "mustBeLessThan": lambda: actual < low,
            "mustBeLessOrEqualTo": lambda: actual <= low,
            "mustBeBetween": lambda: low <= actual <= high,
            "mustNotBeBetween": lambda: actual < low or actual > high,
        }[self.operator]()

    def actual(self, failed_rows: int, total_rows: int) -> float:
        """The value the threshold applies to (see ``measure``)."""
        return measure(self.metric, self.unit, failed_rows, total_rows)


def measure(metric: str, unit: str, failed_rows: int, total_rows: int) -> float:
    """A measured value: rows, or percent of the rows of the table (0 for an empty table).

    ``rowCount`` measures the rows of the table, the other metrics the failed rows.
    """
    count = total_rows if metric == ROW_COUNT else failed_rows
    if unit == PERCENT:
        return 100 * count / total_rows if total_rows else 0.0
    return float(count)


def rule_thresholds(rule: QualityRule, metric: str = FAILED_ROWS) -> list[Threshold]:
    """Returns the thresholds of a quality rule, in the order of the ODCS operators.

    The unit is only read when the rule has thresholds.

    Args:
        rule: The rule.
        metric: What the thresholds measure: ``failedRows``, or ``rowCount`` for a
            ``rowCount`` rule.

    Raises:
        ContractError: If a threshold is not a number (a pair of numbers for the
            ``Between`` operators), a percentage is not from 0 to 100, the unit is not
            ``rows`` or ``percent``, or a ``rowCount`` is in percent.
    """
    if not rule.thresholds:
        return []
    name = f"quality rule {rule.name or rule.metric or rule.type!r}"
    unit = _UNITS.get((rule.unit or ROWS).strip().lower())
    if unit is None:
        raise ContractError(f"{name}: the unit must be rows or percent, got {rule.unit!r}")
    if metric == ROW_COUNT and unit == PERCENT:
        raise ContractError(f"{name}: a rowCount threshold is a number of rows, not a percentage")
    thresholds = []
    for operator, value in rule.thresholds.items():
        if operator in _BETWEEN:
            if isinstance(value, (str, bytes)) or not isinstance(value, Sequence) or len(value) != 2:
                raise ContractError(f"{name}: {operator} must be a pair of numbers [low, high], got {value!r}")
            low, high = (_number(name, operator, item) for item in value)
            if low > high:
                raise ContractError(f"{name}: {operator}: the low bound {low!r} is above the high bound {high!r}")
            threshold = Threshold(operator, low, high, unit, metric)
        else:
            threshold = Threshold(operator, _number(name, operator, value), None, unit, metric)
        if unit == PERCENT and not all(0 <= bound <= 100 for bound in _bounds(threshold)):
            raise ContractError(f"{name}: {operator}: a percentage is from 0 to 100, got {value!r}")
        thresholds.append(threshold)
    return thresholds


def _number(name: str, operator: str, value: object) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        raise ContractError(f"{name}: {operator} must be a number, got {value!r}")
    return float(value)


def _bounds(threshold: Threshold) -> list[float]:
    return [threshold.value] if threshold.high is None else [threshold.value, threshold.high]


@dataclass(frozen=True)
class SummaryRow:
    """A row of the summary table: a measure of a table, or of one of its checks."""

    checked_at: datetime
    run_id: str | None
    data_product: str
    table_name: str
    check_name: str | None
    criticality: str | None
    columns: tuple[str, ...] | None
    metric: str
    total_rows: int
    failed_rows: int
    actual: float
    unit: str
    operator: str | None
    threshold: float | None
    threshold_high: float | None
    passed: bool | None


# The columns of the summary table, in the order of SummaryRow: SQL type and comment.
COLUMNS: Mapping[str, tuple[str, str]] = {
    "checked_at": ("TIMESTAMP", "Start of the run of the quality service, shared by the rows of the run."),
    "run_id": ("STRING", "The run_id runtime parameter of the quality service, such as the job run."),
    "data_product": ("STRING", "Qualified name of the data product: <group>.<data product>."),
    "table_name": ("STRING", "Name of the checked table, in its schema."),
    "check_name": ("STRING", "Name of the DQX check; NULL for the measures of the table."),
    "criticality": ("STRING", "Criticality of the check: error or warn."),
    "columns": ("ARRAY<STRING>", "Columns of the check."),
    "metric": ("STRING", "What is measured: errorRate, warningRate, failedRows or rowCount."),
    "total_rows": ("BIGINT", "Rows of the table."),
    "failed_rows": ("BIGINT", "Rows with errors (errorRate), warnings (warningRate), or flagged by the check."),
    "actual": ("DOUBLE", "Measured value, in unit."),
    "unit": ("STRING", "Unit of actual and of the threshold: rows or percent."),
    "operator": ("STRING", "ODCS operator of the threshold, such as mustBeLessThan; NULL without threshold."),
    "threshold": ("DOUBLE", "Threshold of the contract; the low bound of mustBeBetween and mustNotBeBetween."),
    "threshold_high": ("DOUBLE", "High bound of mustBeBetween and mustNotBeBetween."),
    "passed": ("BOOLEAN", "Whether actual meets the threshold; NULL without threshold."),
}

TABLE_COMMENT = (
    "Quality summary of the tables of the schema, appended by each run of the quality service: "
    "the statistics of the tables and of their checks, against the thresholds of their contracts."
)


def summary_table(table: Table, context: ServiceContext) -> str | None:
    """Returns the unquoted full name of the summary table of a table; ``None`` without summary.

    Raises:
        ConfigurationError: If the name is invalid, or that of a table of the data product.
    """
    settings = table.settings(QualitySettings)
    if not settings.summary:
        return None
    full_name = context.full_table_name(table, resolved(settings.summary_table))
    for other in table.data_product.tables:
        if context.full_table_name(other).lower() == full_name.lower():
            raise ConfigurationError(
                f"{table.qualified_name}: the quality summary table {full_name} is the table "
                f"{other.qualified_name}: set another QualitySettings.summary_table."
            )
    return full_name


def summary_rows(
    *,
    checked_at: datetime,
    run_id: str | None,
    data_product: str,
    table_name: str,
    checks: Sequence[Mapping[str, Any]],
    thresholds: Mapping[str, Sequence[Threshold]],
    error_rate: Threshold | None,
    total_rows: int,
    error_rows: int,
    warning_rows: int,
    failures: Mapping[str, int],
) -> list[SummaryRow]:
    """Returns the summary rows of a checked table.

    Args:
        checked_at: Start of the run.
        run_id: The run, if known.
        data_product: Qualified name of the data product.
        table_name: Name of the table.
        checks: The DQX checks applied to the table.
        thresholds: The thresholds of the checks, by check name.
        error_rate: The ``errorRate`` SLA of the table, if any.
        total_rows: Rows of the table.
        error_rows: Rows with errors.
        warning_rows: Rows with warnings.
        failures: Rows flagged by each check, by check name. The checks missing from
            ``checks``, such as checks DQX named, are added after them.
    """

    def row(
        metric: str,
        failed: int,
        threshold: Threshold | None,
        check: str | None = None,
        details: Mapping[str, Any] | None = None,
    ) -> SummaryRow:
        # Without threshold, the measures of the table are rates, those of the checks rows.
        unit = threshold.unit if threshold else PERCENT if check is None else ROWS
        actual = measure(metric, unit, failed, total_rows)
        return SummaryRow(
            checked_at=checked_at,
            run_id=run_id,
            data_product=data_product,
            table_name=table_name,
            check_name=check,
            criticality=_criticality(details) if details is not None else None,
            columns=_columns(details) if details is not None else None,
            metric=metric,
            total_rows=total_rows,
            failed_rows=failed,
            actual=actual,
            unit=unit,
            operator=threshold.operator if threshold else None,
            threshold=threshold.value if threshold else None,
            threshold_high=threshold.high if threshold else None,
            passed=threshold.passes(actual) if threshold else None,
        )

    rows = [row(ERROR_RATE, error_rows, error_rate), row(WARNING_RATE, warning_rows, None)]
    by_name: dict[str, Mapping[str, Any]] = {}
    for check in checks:
        name = check.get("name")
        if isinstance(name, str) and name:
            by_name.setdefault(name, check)
    for name in [*by_name, *sorted(set(failures) - set(by_name))]:
        failed = failures.get(name, 0)
        details = by_name.get(name, {})
        held: Sequence[Threshold | None] = thresholds.get(name) or [None]
        for threshold in held:
            metric = threshold.metric if threshold else FAILED_ROWS
            rows.append(row(metric, failed, threshold, name, details))
    return rows


def _criticality(check: Mapping[str, Any]) -> str | None:
    if not check:
        return None
    criticality = check.get("criticality")
    # DQX checks are errors by default.
    return str(criticality) if criticality else "error"


def _columns(check: Mapping[str, Any]) -> tuple[str, ...] | None:
    arguments = (check.get("check") or {}).get("arguments") or {}
    columns = arguments.get("columns")
    if columns is None and arguments.get("column") is not None:
        columns = [arguments["column"]]
    if isinstance(columns, (str, bytes)) or not isinstance(columns, Sequence):
        return None
    # The aggregate checks, such as the row count, apply to all the columns (*).
    names = tuple(str(column) for column in columns if column != "*")
    return names or None


def create_statement(full_name: str) -> str:
    """Returns the statement creating the summary table, if it does not exist."""
    definitions = ",\n  ".join(
        f"{quote_identifier(name)} {data_type} COMMENT {string_literal(comment)}"
        for name, (data_type, comment) in COLUMNS.items()
    )
    return (
        f"CREATE TABLE IF NOT EXISTS {quote_name(full_name)} (\n  {definitions}\n)\n"
        f"USING DELTA\nCOMMENT {string_literal(TABLE_COMMENT)}"
    )


def insert_statement(full_name: str, rows: Sequence[SummaryRow]) -> str:
    """Returns the statement appending rows to the summary table."""
    values = ",\n  ".join(
        "(" + ", ".join(_literal(getattr(row, name), data_type) for name, (data_type, _) in COLUMNS.items()) + ")"
        for row in rows
    )
    columns = ", ".join(quote_identifier(name) for name in COLUMNS)
    return f"INSERT INTO {quote_name(full_name)} ({columns}) VALUES\n  {values}"


def _literal(value: object, data_type: str) -> str:
    if value is None:
        return f"CAST(NULL AS {data_type})"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, datetime):
        # The offset makes the time independent of the time zone of the session.
        return f"TIMESTAMP {string_literal(value.isoformat(sep=' '))}"
    if isinstance(value, tuple):
        return f"array({', '.join(string_literal(str(item)) for item in value)})"
    if isinstance(value, (int, float)):
        return f"{float(value)!r}D" if data_type == "DOUBLE" else str(int(value))
    return string_literal(str(value))


def failures_query(full_name: str, result_columns: Sequence[str]) -> str | None:
    """Returns the query counting the rows flagged by each check: ``name`` and ``failed_rows``.

    Args:
        full_name: The checked table.
        result_columns: Its DQX result columns holding errors and warnings, whose items
            name their check.

    Returns:
        The query; ``None`` without result column.
    """
    names = [
        f"coalesce(transform({quote_identifier(column)}, r -> r.name), CAST(array() AS ARRAY<STRING>))"
        for column in result_columns
    ]
    if not names:
        return None
    # A check is counted once per row, whatever the column and the number of its results.
    expression = names[0]
    for other in names[1:]:
        expression = f"array_union({expression}, {other})"
    return (
        "SELECT name, count(*) AS failed_rows\n"
        f"FROM (SELECT explode(array_distinct({expression})) AS name FROM {quote_name(full_name)}) AS results\n"
        "WHERE name IS NOT NULL\nGROUP BY name"
    )


def summary_tables(tables: Sequence[Table], context: ServiceContext) -> dict[str, list[str]]:
    """The summary tables of tables, by full name, with the names of their tables.

    The tables without summary are left out (``QualitySettings.summary``).

    Raises:
        ConfigurationError: If the name of a summary table is invalid (see ``summary_table``).
    """
    found: dict[str, list[str]] = {}
    for table in tables:
        full_name = summary_table(table, context)
        if full_name:
            found.setdefault(full_name, []).append(table.name)
    return found


def latest_thresholds_query(summaries: Mapping[str, Sequence[str]], data_product: str) -> str:
    """Query of the latest summary rows with a threshold of the tables of a data product.

    The rows of the latest run of each table (``checked_at``), with a threshold: its
    ``errorRate`` and the checks of the rules with thresholds. Columns: ``table_name``,
    ``measure`` (the check, or the metric of the table), ``criticality``, ``metric``,
    ``actual``, ``unit``, ``operator``, ``threshold``, ``threshold_high``, ``passed``,
    ``checked_at`` and ``run_id``.

    Args:
        summaries: The summary tables, by unquoted full name, with the names of the tables
            to read (see ``summary_tables``): the rows of the other tables, such as tables
            removed from the data product, are left out.
        data_product: Qualified name of the data product.
    """
    selects = [
        f"  SELECT * FROM {quote_name(full_name)}\n"
        f"  WHERE data_product = {string_literal(data_product)} "
        f"AND table_name IN ({', '.join(string_literal(name) for name in names)})"
        for full_name, names in summaries.items()
    ]
    return (
        "SELECT table_name, coalesce(check_name, metric) AS measure, criticality, metric, actual, unit,\n"
        "  operator, threshold, threshold_high, passed, checked_at, run_id\n"
        "FROM (\n"
        # The latest run of each table, before keeping the rows with a threshold.
        "  SELECT *, max(checked_at) OVER (PARTITION BY table_name) AS latest_checked_at\n"
        "  FROM (\n" + "\n  UNION ALL\n".join(selects) + "\n  ) AS summary\n"
        ") AS runs\n"
        "WHERE checked_at = latest_checked_at AND passed IS NOT NULL"
    )
