"""Dashboard service: creates, updates and publishes the quality dashboard of a data product."""

from __future__ import annotations

import json
import logging
from collections.abc import Mapping
from typing import TYPE_CHECKING, Any

from cds.config import DashboardSettings
from cds.dashboard import build_dashboard
from cds.services.base import TableResult
from cds.services.checks import checked_tables
from cds.services.tags import discover_domains
from cds.services.workspace import DataProductService, folder

if TYPE_CHECKING:
    from cds.data_context import DataProduct

logger = logging.getLogger(__name__)

# Schema property holding the id of the quality dashboard of the data product of the schema.
DASHBOARD_PROPERTY = "cds.dashboard_id"
# Schema property recording the Discover domains the service tagged the dashboard with.
DOMAINS_PROPERTY = "cds.dashboard_domains"
# Runtime parameters of the service.
WAREHOUSE_PARAMETER = "dashboard_warehouse_id"
PARENT_PATH_PARAMETER = "dashboard_parent_path"
DASHBOARDS_PATH = "/api/2.0/lakeview/dashboards"
TRASHED = "TRASHED"


class DashboardService(DataProductService):
    """Creates the quality dashboard of a data product, or updates it, and publishes it.

    The dashboard is generated by ``cds.dashboard.build_dashboard``, with the tables of the
    environment, and titled ``<title> (<environment>)``. Its id is kept in the
    ``cds.dashboard_id`` property of the schema of the data product: the next runs update
    that dashboard, or create a new one if it was deleted. A dashboard that already matches
    the contracts is left unchanged, and published again only if it is not published.

    The dashboard is published with embedded credentials: its viewers see the data with the
    permissions of the user running the service, who needs ``CAN USE`` on the warehouse.
    The columns it may not show are left out of its queries (see ``DashboardSettings``).

    With ``MetadataSettings.discover_domain``, the dashboard joins the Discover domains of
    its tables: it gets their governed tags, which the user running the service needs
    ``ASSIGN`` on. A dashboard that cannot be tagged is reported as a warning.

    The service processes a data product, not its tables: it reports a single result,
    named after the data product. It is skipped when ``DashboardSettings.enabled`` is not set.

    Runtime parameters:

    - ``dashboard_warehouse_id``: the SQL warehouse running the queries of the dashboard.
      Required.
    - ``dashboard_parent_path``: the workspace folder of a new dashboard, such as
      ``/Workspace/Shared/dashboards``. By default, the home folder of the user running the
      service. An existing dashboard is not moved: the service warns when it is in another
      folder.
    """

    name = "dashboard"
    object_name = "dashboard"

    def synchronize(self, data_product: DataProduct) -> TableResult:
        """Creates or updates the dashboard of a data product, publishes it, and returns its result."""
        name = data_product.qualified_name
        if not data_product.settings(DashboardSettings).enabled:
            return TableResult.skipped(name, "no dashboard: DashboardSettings.enabled is not set")
        runtime = self.context.runtime_configuration
        tables = checked_tables(data_product, self.context)
        dashboard = build_dashboard(data_product, self.context, tables)
        warehouse_id = runtime.require(WAREHOUSE_PARAMETER)
        body: dict[str, Any] = {
            "display_name": f"{dashboard['title']} ({self.context.environment})",
            "warehouse_id": warehouse_id,
            "serialized_dashboard": json.dumps(dashboard["serialized_dashboard"], ensure_ascii=False),
        }
        parent_path = runtime.get(PARENT_PATH_PARAMETER)

        domains = discover_domains(tables)
        schema = self.context.full_schema_name(data_product)
        properties = self.schema_properties(schema)
        dashboard_id = properties.get(DASHBOARD_PROPERTY)
        existing = self.get_or_none(f"{DASHBOARDS_PATH}/{dashboard_id}") if dashboard_id else None
        # Unlike Genie spaces, a dashboard in the trash can still be read.
        if existing is not None and existing.get("lifecycle_state") == TRASHED:
            existing = None
        if dashboard_id and existing is None:
            logger.warning("dashboard: the dashboard %s of %s no longer exists: creating a new one", dashboard_id, name)
        warnings = []
        if existing is None:
            created = self.api.do(
                "POST", DASHBOARDS_PATH, body={**body, "parent_path": parent_path} if parent_path else body
            )
            dashboard_id = str(created["dashboard_id"])
            self.record_id(schema, DASHBOARD_PROPERTY, dashboard_id, f"{DASHBOARDS_PATH}/{dashboard_id}")
            action = "created"
        elif _matches(existing, body):
            action = "unchanged"
        else:
            self.api.do("PATCH", f"{DASHBOARDS_PATH}/{dashboard_id}", body=body)
            action = "updated"
        if existing is not None and parent_path and folder(existing.get("parent_path")) != folder(parent_path):
            warnings.append(f"it is in {existing.get('parent_path')}, not in {parent_path}: move it there")
        published = self._publish(str(dashboard_id), warehouse_id, force=action != "unchanged")
        message = f"{action} the dashboard {dashboard_id} ({body['display_name']}), {published}"
        problem = self.tag_domains("dashboards", str(dashboard_id), domains, schema, properties, DOMAINS_PROPERTY)
        if problem:
            warnings.append(problem)
        elif domains:
            message += f", in the Discover domain(s) {', '.join(domains)}"
        if warnings:
            return TableResult.warning(name, f"{message}; {'; '.join(warnings)}")
        return TableResult.success(name, message)

    def _publish(self, dashboard_id: str, warehouse_id: str, *, force: bool) -> str:
        """Publishes the dashboard with embedded credentials, unless it already is; returns what was done."""
        path = f"{DASHBOARDS_PATH}/{dashboard_id}/published"
        if not force:
            published = self.get_or_none(path)
            if (
                published is not None
                and published.get("embed_credentials")
                and (published.get("warehouse_id") == warehouse_id)
            ):
                return "already published"
        self.api.do("POST", path, body={"embed_credentials": True, "warehouse_id": warehouse_id})
        return "published"


def _matches(existing: Mapping[str, Any], body: Mapping[str, Any]) -> bool:
    """Whether an existing dashboard already has the configuration of a request."""
    try:
        serialized = json.loads(existing.get("serialized_dashboard") or "null")
    except ValueError:
        return False
    if serialized != json.loads(body["serialized_dashboard"]):
        return False
    return all(existing.get(key) == body.get(key) for key in ("display_name", "warehouse_id"))
