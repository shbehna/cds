"""Metrics service: creates or updates the metric views of the tables, from their contracts."""

from __future__ import annotations

import logging
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, field
from typing import TYPE_CHECKING

from cds.config import MetadataSettings, MetricViewSettings, resolved
from cds.errors import CdsError
from cds.metric_views import DELIMITER, MetricView, build_metric_view
from cds.semantics import metric_view_name
from cds.services.base import Service, ServiceReport, TableResult
from cds.services.tables import list_tables
from cds.services.tags import certification_value, discover_domain, tag_changes
from cds.sql import quote_identifier, quote_name, set_tags_statement, string_literal, unset_tags_statement

if TYPE_CHECKING:
    from cds.data_context import DataProduct, Table

logger = logging.getLogger(__name__)

# Properties of the metric views created by the service: the table of each, and the
# digest of its YAML, which Unity Catalog stores rewritten.
SOURCE_PROPERTY = "cds.metric_view"
DIGEST_PROPERTY = "cds.metric_view_digest"
METRIC_VIEW_TYPE = "METRIC_VIEW"
VIEW = "VIEW"


@dataclass
class _Schema:
    """What a schema holds: its tables and views, its metric views and their properties and tags."""

    objects: set[str] = field(default_factory=set)
    properties: dict[str, dict[str, str]] = field(default_factory=dict)
    tags: dict[str, dict[str, str]] = field(default_factory=dict)


class MetricsService(Service):
    """Creates the metric view of each table whose contract declares measures, or updates it.

    The metric views are generated by ``cds.metric_views``, in the schema of their table,
    when ``MetricViewSettings.enabled`` is set. A new metric view is created with the
    ``cds.metric_view`` property, naming its table, and ``cds.metric_view_digest``, the
    digest of its YAML: the next runs update the definition of a view whose digest
    differs (``ALTER VIEW ... AS``, which keeps its tags and grants), and leave the others
    unchanged. When the service processes all the tables, it drops the metric views it
    created that the contracts no longer declare. It never replaces a table, a view or a
    metric view it did not create: their name is reported as an error.

    With ``MetadataSettings.tags``, the metric view gets the certification of its table,
    and joins its Discover domain in the environments of
    ``MetadataSettings.discover_environments``. The other tags of the view are left
    untouched.

    The user running the service needs ``CREATE TABLE`` on the schema, ``SELECT`` on the
    tables, and ``ASSIGN`` on the governed tags.
    """

    name = "metrics"

    def prepare(self, data_product: DataProduct, tables: Sequence[Table]) -> None:
        self._schemas: dict[str, _Schema] = {}
        for full_schema_name in sorted({self.context.full_schema_name(table) for table in data_product.tables}):
            self._schemas[full_schema_name] = self._read_schema(full_schema_name)

    def run(
        self,
        data_product: DataProduct,
        tables: Iterable[str] | None = None,
        max_workers: int | None = None,
    ) -> ServiceReport:
        """Processes the tables of a data product; with all of them, also drops the metric views no longer declared."""
        report = super().run(data_product, tables, max_workers)
        if not tables:
            report.results.extend(self._drop_stale(data_product))
        return report

    def process(self, table: Table) -> TableResult:
        if not table.settings(MetricViewSettings).enabled:
            return TableResult.skipped(table.qualified_name, "no metric view: MetricViewSettings.enabled is not set")
        view = build_metric_view(table, self.context)
        if view is None:
            return TableResult.skipped(table.qualified_name, "no metric view: the contract declares no measures")
        full_schema_name = self.context.full_schema_name(table)
        schema = self._schemas[full_schema_name]
        full_name = f"{full_schema_name}.{view.name}"
        properties = schema.properties.get(view.name.lower())
        if properties is None or properties.get(SOURCE_PROPERTY) != table.name:
            if properties is not None or view.name.lower() in schema.objects:
                return TableResult.failure(
                    table.qualified_name, f"{full_name} exists and is not the metric view of the table: rename one"
                )
            self.spark.sql(create_statement(full_name, view))
            action = "created"
        elif properties.get(DIGEST_PROPERTY) != view.digest:
            for statement in update_statements(full_name, view):
                self.spark.sql(statement)
            action = "updated"
        else:
            action = "unchanged"
        tags = self._tag_statements(table, full_name, schema.tags.get(view.name.lower(), {}))
        for statement in tags:
            self.spark.sql(statement)
        message = f"{action} the metric view {full_name}: {_details(view)}"
        if tags:
            message += f", {len(tags)} tag statement(s)"
        return TableResult.success(table.qualified_name, message)

    def _tag_statements(self, table: Table, full_name: str, actual: Mapping[str, str]) -> list[str]:
        """The statements giving a metric view the certification and the Discover domain of its table."""
        settings = table.settings(MetadataSettings)
        if not settings.tags:
            return []
        expected: dict[str, str] = {}
        certification = certification_value(table)
        certification_tag = resolved(settings.certification_tag)
        if certification:
            expected[certification_tag] = certification
        domain = discover_domain(table, self.context.environment.id)
        if domain:
            expected[domain] = ""
        # The tags of the service: the certification, and the domain in every environment.
        managed = {certification_tag, *([tag] if (tag := discover_domain(table)) else [])}
        changes = tag_changes(expected, actual, managed)
        statements = [set_tags_statement(full_name, dict(changes.set), kind=VIEW)] if changes.set else []
        if changes.unset:
            statements.append(unset_tags_statement(full_name, changes.unset, kind=VIEW))
        return statements

    def _drop_stale(self, data_product: DataProduct) -> list[TableResult]:
        """Drops the metric views the service created that no table of the data product declares anymore."""
        expected: dict[str, set[str]] = {}
        for table in data_product.tables:
            name = self._view_name(table)
            if name:
                expected.setdefault(self.context.full_schema_name(table), set()).add(name.lower())
        results = []
        for full_schema_name, schema in self._schemas.items():
            for name, properties in sorted(schema.properties.items()):
                if SOURCE_PROPERTY not in properties or name in expected.get(full_schema_name, set()):
                    continue
                full_name = f"{full_schema_name}.{name}"
                try:
                    self.spark.sql(f"DROP VIEW IF EXISTS {quote_name(full_name)}")
                except Exception as exc:
                    logger.exception("metrics: cannot drop the metric view %s", full_name)
                    results.append(TableResult.failure(full_name, f"{type(exc).__name__}: {exc}", exc))
                    continue
                results.append(TableResult.success(full_name, f"dropped the metric view {full_name}: no measures"))
        return results

    def _view_name(self, table: Table) -> str | None:
        """The name of the metric view of a table; a table whose measures are invalid keeps its view."""
        try:
            return metric_view_name(table)
        except CdsError:
            settings = table.settings(MetricViewSettings)
            return resolved(settings.name).format(table=table.name) if settings.enabled else None

    def _read_schema(self, full_schema_name: str) -> _Schema:
        catalog, schema_name = full_schema_name.split(".")
        information_schema = f"{quote_identifier(catalog)}.`information_schema`"
        schema = _Schema(objects=list_tables(self.spark, full_schema_name))
        if not schema.objects:
            return schema
        views = self.spark.sql(
            f"SELECT table_name FROM {information_schema}.`tables` WHERE table_schema = {string_literal(schema_name)} "
            f"AND table_type = {string_literal(METRIC_VIEW_TYPE)}"
        ).collect()
        for row in views:
            name = str(row.table_name)
            rows = self.spark.sql(f"SHOW TBLPROPERTIES {quote_name(f'{full_schema_name}.{name}')}").collect()
            schema.properties[name.lower()] = {str(item.key): str(item.value) for item in rows}
        for row in self.spark.sql(
            f"SELECT table_name, tag_name, tag_value FROM {information_schema}.`table_tags` "
            f"WHERE schema_name = {string_literal(schema_name)}"
        ).collect():
            if str(row.table_name).lower() in schema.properties:
                schema.tags.setdefault(str(row.table_name).lower(), {})[row.tag_name] = row.tag_value or ""
        return schema


def create_statement(full_name: str, view: MetricView) -> str:
    """The statement creating a metric view, with the properties of the service."""
    properties = f"{string_literal(SOURCE_PROPERTY)} = {string_literal(view.table.name)}, "
    properties += f"{string_literal(DIGEST_PROPERTY)} = {string_literal(view.digest)}"
    return (
        f"CREATE VIEW {quote_name(full_name)} WITH METRICS LANGUAGE YAML TBLPROPERTIES ({properties}) "
        f"AS {DELIMITER}\n{view.yaml}{DELIMITER}"
    )


def update_statements(full_name: str, view: MetricView) -> list[str]:
    """The statements updating the definition of a metric view, then its digest."""
    return [
        f"ALTER VIEW {quote_name(full_name)} AS {DELIMITER}\n{view.yaml}{DELIMITER}",
        f"ALTER VIEW {quote_name(full_name)} SET TBLPROPERTIES "
        f"({string_literal(DIGEST_PROPERTY)} = {string_literal(view.digest)})",
    ]


def _details(view: MetricView) -> str:
    fields = len(view.definition["fields"])
    joins = len(view.definition.get("joins", []))
    return f"{fields} dimension(s), {len(view.measures)} measure(s), {joins} join(s)"
