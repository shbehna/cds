"""Genie service: creates or updates the Genie space of a data product."""

from __future__ import annotations

import json
import logging
from collections.abc import Iterable, Mapping
from typing import TYPE_CHECKING, Any
from urllib.parse import quote

from cds.config import GenieSettings
from cds.errors import ConfigurationError
from cds.genie import build_space
from cds.services.base import Service, ServiceReport, TableResult
from cds.sql import quote_name, string_literal

if TYPE_CHECKING:
    from cds.data_context import DataProduct, Table

logger = logging.getLogger(__name__)

# Schema property holding the id of the Genie space of the data product of the schema.
SPACE_PROPERTY = "cds.genie_space_id"
# Runtime parameters of the service.
WAREHOUSE_PARAMETER = "genie_warehouse_id"
PARENT_PATH_PARAMETER = "genie_parent_path"
SPACES_PATH = "/api/2.0/genie/spaces"
SCHEMAS_PATH = "/api/2.1/unity-catalog/schemas"
WORKSPACE_PREFIX = "/Workspace"


class GenieService(Service):
    """Creates the Genie space of a data product, or updates it to match its contracts.

    The space is generated by ``cds.genie.build_space``, with the tables of the
    environment, and titled ``<title> (<environment>)``. Its id is kept in the
    ``cds.genie_space_id`` property of the schema of the data product: the next runs
    update that space, or create a new one if it was deleted. A space that already
    matches the contracts is left unchanged.

    The service processes a data product, not its tables: it reports a single result,
    named after the data product. It is skipped when ``GenieSettings.enabled`` is not set.

    Runtime parameters:

    - ``genie_warehouse_id``: the SQL warehouse running the queries of the space. Required.
    - ``genie_parent_path``: the workspace folder of the space, such as
      ``/Workspace/Shared/genie``. By default, the home folder of the user running the
      service. The users of the space are granted access on the folder: a space inherits
      the permissions of its folder.

    The space runs its queries with the permissions of each user, on its warehouse: they
    need ``CAN USE`` on the warehouse and ``SELECT`` on the tables, and column masks and row
    filters apply.
    """

    name = "genie"

    def run(
        self,
        data_product: DataProduct,
        tables: Iterable[str] | None = None,
        max_workers: int | None = None,
    ) -> ServiceReport:
        """Creates or updates the Genie space of a data product.

        The space has all the tables of the data product: ``tables`` and
        ``max_workers`` are ignored.
        """
        if tables:
            logger.info("genie: the space has all the tables of %s, not only %s", data_product.qualified_name, tables)
        try:
            result = self.synchronize(data_product)
        except Exception as exc:
            logger.exception("genie: the Genie space of %s failed", data_product.qualified_name)
            result = TableResult.failure(data_product.qualified_name, f"{type(exc).__name__}: {exc}", exc)
        return ServiceReport(self.name, data_product.qualified_name, [result])

    def process(self, table: Table) -> TableResult:
        raise ConfigurationError("The genie service processes data products, not tables: call run.")

    def synchronize(self, data_product: DataProduct) -> TableResult:
        """Creates or updates the Genie space of a data product, and returns its result."""
        name = data_product.qualified_name
        if not data_product.settings(GenieSettings).enabled:
            return TableResult.skipped(name, "no Genie space: GenieSettings.enabled is not set")
        runtime = self.context.runtime_configuration
        space = build_space(data_product, self.context)
        body: dict[str, Any] = {
            "title": f"{space['title']} ({self.context.environment})",
            "warehouse_id": runtime.require(WAREHOUSE_PARAMETER),
            "serialized_space": json.dumps(space["serialized_space"], ensure_ascii=False),
            # Always sent: an empty description clears that of the space.
            "description": space["description"] or "",
        }
        parent_path = runtime.get(PARENT_PATH_PARAMETER)
        if parent_path:
            body["parent_path"] = parent_path

        schema = self.context.full_schema_name(data_product)
        space_id = self._stored_space_id(schema)
        existing = self._get_space(space_id) if space_id else None
        if space_id and existing is None:
            logger.warning("genie: the Genie space %s of %s no longer exists: creating a new one", space_id, name)
        if existing is None:
            created = self._api.do("POST", SPACES_PATH, body=body)
            space_id = str(created["space_id"])
            self._record_space_id(schema, space_id)
            action = "created"
        elif _matches(existing, body):
            action = "unchanged"
        else:
            # The update also moves the space to the folder of the request.
            self._api.do("PATCH", f"{SPACES_PATH}/{space_id}", body=body)
            action = "updated"
        serialized = space["serialized_space"]
        details = (
            f"{len(serialized['data_sources']['tables'])} table(s), "
            f"{len(serialized['instructions']['join_specs'])} join(s), "
            f"{len(serialized['instructions']['example_question_sqls'])} example(s)"
        )
        return TableResult.success(name, f"{action} the Genie space {space_id} ({body['title']}): {details}")

    @property
    def _api(self) -> Any:
        return self.context.workspace_client.api_client

    def _stored_space_id(self, schema: str) -> str | None:
        """The id of the space recorded in the properties of the schema, if any."""
        found = self._api.do("GET", f"{SCHEMAS_PATH}/{quote(schema, safe='')}")
        properties = (found.get("properties") if isinstance(found, Mapping) else None) or {}
        value = properties.get(SPACE_PROPERTY)
        return str(value) if value else None

    def _record_space_id(self, schema: str, space_id: str) -> None:
        """Records the id of a new space in the properties of the schema.

        If it cannot be recorded, the space is deleted, and the error raised: the next run
        would not find the space, and would create another one.
        """
        try:
            self.spark.sql(
                f"ALTER SCHEMA {quote_name(schema)} SET DBPROPERTIES "
                f"({string_literal(SPACE_PROPERTY)} = {string_literal(space_id)})"
            )
        except Exception:
            logger.error("genie: cannot record the Genie space %s in %s: deleting it", space_id, schema)
            try:
                self._api.do("DELETE", f"{SPACES_PATH}/{space_id}")
            except Exception:
                logger.exception("genie: cannot delete the Genie space %s", space_id)
            raise

    def _get_space(self, space_id: str) -> Mapping[str, Any] | None:
        """The space with its serialized configuration, ``None`` if it does not exist.

        A deleted space is in the trash: the API answers ``NOT_FOUND`` for it.
        """
        from databricks.sdk.errors import NotFound

        try:
            found = self._api.do("GET", f"{SPACES_PATH}/{space_id}", query={"include_serialized_space": "true"})
        except NotFound:
            return None
        return found if isinstance(found, Mapping) else None


def _matches(existing: Mapping[str, Any], body: Mapping[str, Any]) -> bool:
    """Whether an existing space already has the configuration of a request.

    The API returns the serialized space as it was sent: the configurations are compared
    as parsed JSON.
    """
    try:
        serialized = json.loads(existing.get("serialized_space") or "null")
    except ValueError:
        return False
    if serialized != json.loads(body["serialized_space"]):
        return False
    if "parent_path" in body and _folder(existing.get("parent_path")) != _folder(body["parent_path"]):
        return False
    keys = ("title", "warehouse_id", "description")
    return all((existing.get(key) or None) == (body.get(key) or None) for key in keys)


def _folder(path: object) -> str | None:
    """A workspace folder without its ``/Workspace`` prefix nor trailing slash, as the API may return it."""
    if not isinstance(path, str):
        return None
    path = path.rstrip("/")
    return path.removeprefix(WORKSPACE_PREFIX) if path.startswith(f"{WORKSPACE_PREFIX}/") else path
