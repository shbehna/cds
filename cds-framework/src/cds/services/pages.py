"""Pages service: creates or updates the Pages of a data product in its Discover domains."""

from __future__ import annotations

import json
import logging
import re
from collections import Counter
from collections.abc import Mapping
from typing import TYPE_CHECKING, Any

from cds.config import PagesSettings
from cds.pages import Page, build_pages
from cds.services.base import TableResult
from cds.services.workspace import DataProductService

if TYPE_CHECKING:
    from cds.data_context import DataProduct

logger = logging.getLogger(__name__)

# Schema property holding the ids of the Pages of the data product of the schema, by key.
PAGES_PROPERTY = "cds.knowledge_pages"
PAGES_PATH = "/api/2.0/knowledge/pages"
KNOWLEDGE_PATH = "/api/2.0/knowledge"
DOMAINS_PATH = "/api/2.0/domains"
# Fields of a Page the service sets, compared to update only those that changed.
FIELDS = ("domain", "display_name", "description", "body", "synonyms", "state")
# Name of a Page in the API: pages/<id>.
_PAGE_NAME = re.compile(r"^pages/[A-Za-z0-9-]+$")


class PagesService(DataProductService):
    """Creates the Pages of a data product, or updates them to match its contracts.

    The Pages are generated by ``cds.pages.build_pages``, in the Discover domains of the
    tables: published in the environments of ``MetadataSettings.discover_environments``,
    drafts in the others. Their ids are kept, by key, in the ``cds.knowledge_pages``
    property of the schema of the data product: the next runs update those Pages, create
    them again if they were deleted, and delete those the contracts no longer describe,
    such as the Page of a removed table or of a deprecated contract. A Page that already
    matches the contracts is left unchanged.

    The service processes a data product, not its tables: it reports a single result,
    named after the data product. It is skipped when ``PagesSettings.enabled`` is not set,
    or when no table is in a Discover domain. A Page whose domain does not exist, or whose
    title is already that of another published Page of its domain, is reported as a
    warning; the others are processed.

    The user running the service needs ``MANAGE PAGES`` on the domains, which all the
    users of the account have by default.
    """

    name = "pages"
    object_name = "Pages"

    def synchronize(self, data_product: DataProduct) -> TableResult:
        """Creates, updates or deletes the Pages of a data product, and returns its result."""
        name = data_product.qualified_name
        if not data_product.settings(PagesSettings).enabled:
            return TableResult.skipped(name, "no Pages: PagesSettings.enabled is not set")
        pages = build_pages(data_product, self.context)
        schema = self.context.full_schema_name(data_product)
        recorded = recorded_pages(self.schema_properties(schema).get(PAGES_PROPERTY))
        if not pages and not recorded:
            return TableResult.skipped(
                name, "no Pages: no table is in a Discover domain (MetadataSettings.discover_domain)"
            )
        domains = self._domains() if pages else {}
        counts: Counter[str] = Counter()
        problems: list[str] = []
        for page in pages:
            domain = domains.get(page.domain)
            if domain is None:
                problems.append(f"{page.display_name!r}: the Discover domain {page.domain!r} does not exist")
                continue
            problem = self._synchronize_page(page, domain, schema, recorded, counts)
            if problem:
                problems.append(problem)
        expected = {page.key for page in pages}
        for key in sorted(set(recorded) - expected):
            self._delete(recorded.pop(key))
            self._record(schema, recorded)
            counts["deleted"] += 1
        actions = ("created", "updated", "unchanged", "deleted")
        message = ", ".join(f"{counts[action]} {action}" for action in actions if counts[action]) or "none"
        message = f"{len(pages)} Page(s): {message}"
        if pages:
            message += f", in the Discover domain(s) {', '.join(sorted({page.domain for page in pages}))}"
        drafts = sum(1 for page in pages if not page.published)
        if drafts:
            message += f" ({drafts} draft(s))"
        if problems:
            return TableResult.warning(name, f"{message}; {'; '.join(problems)}")
        return TableResult.success(name, message)

    def _synchronize_page(
        self, page: Page, domain: str, schema: str, recorded: dict[str, str], counts: Counter[str]
    ) -> str | None:
        """Creates or updates a Page; returns the problem if its title is taken."""
        from databricks.sdk.errors import AlreadyExists, ResourceAlreadyExists

        body = page_body(page, domain)
        page_name = recorded.get(page.key)
        existing = self.get_or_none(f"{KNOWLEDGE_PATH}/{page_name}") if page_name else None
        if page_name and existing is None:
            logger.warning("pages: the Page %s (%s) no longer exists: creating a new one", page_name, page.display_name)
        try:
            if existing is None:
                created = self.api.do("POST", PAGES_PATH, body=body)
                created_name = str(created["name"])
                serialized = _serialized({**recorded, page.key: created_name})
                self.record_id(schema, PAGES_PROPERTY, serialized, f"{KNOWLEDGE_PATH}/{created_name}")
                recorded[page.key] = created_name
                counts["created"] += 1
                return None
            changed = changed_fields(existing, body)
            if not changed:
                counts["unchanged"] += 1
                return None
            self.api.do(
                "PATCH",
                f"{KNOWLEDGE_PATH}/{page_name}",
                query={"update_mask": ",".join(changed)},
                body={key: body[key] for key in changed},
            )
            counts["updated"] += 1
        except (AlreadyExists, ResourceAlreadyExists) as exc:
            logger.warning("pages: the title of the Page %r is taken: %s", page.display_name, exc)
            return f"{page.display_name!r}: another published Page of {page.domain!r} has this title"
        return None

    def _delete(self, page_name: str) -> None:
        """Deletes a Page; one already deleted is ignored."""
        from databricks.sdk.errors import NotFound

        try:
            self.api.do("DELETE", f"{KNOWLEDGE_PATH}/{page_name}")
        except NotFound:
            logger.info("pages: the Page %s was already deleted", page_name)

    def _record(self, schema: str, recorded: Mapping[str, str]) -> None:
        self.set_schema_property(schema, PAGES_PROPERTY, _serialized(recorded))

    def _domains(self) -> dict[str, str]:
        """The names of the Discover domains (``domains/<id>``), by governed tag, from all the pages of the API."""
        domains: dict[str, str] = {}
        query: dict[str, str] = {}
        while True:
            page = self.api.do("GET", DOMAINS_PATH, query=dict(query) if query else None) or {}
            for domain in page.get("domains") or []:
                if domain.get("tag_key") and domain.get("name"):
                    domains[str(domain["tag_key"])] = str(domain["name"])
            token = page.get("next_page_token")
            if not token:
                return domains
            query["page_token"] = str(token)


def page_body(page: Page, domain: str) -> dict[str, Any]:
    """The request creating a Page, in the domain named ``domains/<id>``."""
    return {
        "domain": domain,
        "display_name": page.display_name,
        # Always sent: an empty description clears that of the Page.
        "description": page.description or "",
        "body": page.body,
        "synonyms": list(page.synonyms),
        "state": page.state,
    }


def changed_fields(existing: Mapping[str, Any], body: Mapping[str, Any]) -> list[str]:
    """The fields of a request that an existing Page does not have.

    The API returns the synonyms trimmed, deduplicated and sorted: they are compared as sets.
    """
    changed = []
    for key in FIELDS:
        actual, expected = existing.get(key), body[key]
        if key == "synonyms":
            if set(actual or []) != set(expected):
                changed.append(key)
        elif (actual or None) != (expected or None):
            changed.append(key)
    return changed


def recorded_pages(value: str | None) -> dict[str, str]:
    """The Pages recorded in a schema property, a JSON mapping of key to Page name; none if unreadable."""
    try:
        recorded = json.loads(value or "{}")
    except ValueError:
        return {}
    if not isinstance(recorded, Mapping):
        return {}
    return {
        str(key): page_name
        for key, page_name in recorded.items()
        if isinstance(page_name, str) and _PAGE_NAME.match(page_name)
    }


def _serialized(recorded: Mapping[str, str]) -> str:
    return json.dumps(dict(sorted(recorded.items())), ensure_ascii=False)
